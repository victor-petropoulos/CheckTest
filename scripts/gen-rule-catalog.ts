/**
 * Rule-catalog generator (remediation plan UNIT 3).
 *
 * Regenerates ONLY the marked GENERATED region of docs/rules/catalog.md — the
 * per-rule data tables — from the same RuleMetadata the production CLI
 * registers (src/cli.ts:573-577). Hand-written prose outside the markers is
 * preserved verbatim. The unregistered ct-demo-001 stub is never registered
 * here and therefore never appears in the generated tables.
 *
 * Run strategy (plan UNIT 3 decision, option B): scripts/ is outside tsconfig
 * include=['src','tests'] and the repo has no ts-node/tsx devDependency, so run
 * via `npx tsx scripts/gen-rule-catalog.ts` (the SKILL.md convention). CI runs
 * the same command and fails on `git diff --exit-code -- docs/rules/catalog.md`.
 *
 * Registration below MIRRORS src/cli.ts main(); there is no exported
 * register-only seam in cli.ts (registration is inline in main()). Drift
 * between the two lists is caught by tests/scripts/gen-rule-catalog.test.ts.
 */

import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
import { hasLocalDecisionHook, RuleMetadata } from '../src/core/rule';
import { CT_COV_001 } from '../src/rules/ct-cov-001';
import { CT_INT_001 } from '../src/rules/ct-int-001';
import { CT_INT_003 } from '../src/rules/ct-int-003';
import { CT_INT_004 } from '../src/rules/ct-int-004';
import { CT_MUT_001 } from '../src/rules/ct-mut-001';
import { allRules, registerRule } from '../src/rules/registry';

export const BEGIN_MARKER =
  '<!-- BEGIN GENERATED: rule-data-tables — generated by scripts/gen-rule-catalog.ts; do not edit inside this block -->';
export const END_MARKER = '<!-- END GENERATED: rule-data-tables -->';

/** The production registration set — mirror of src/cli.ts:573-577 (main()). */
export const PRODUCTION_RULES: readonly RuleMetadata[] = [CT_INT_001, CT_INT_003, CT_INT_004, CT_COV_001, CT_MUT_001];

export function registerProductionRules(): void {
  for (const rule of PRODUCTION_RULES) {
    registerRule(rule);
  }
}

/** Escape a value for a single markdown table cell. */
function cell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function evaluationCell(rule: RuleMetadata): string {
  const evaluation = rule.evaluation;
  const parts = [
    `metric \`${evaluation.metric}\`, pass_at_least ${evaluation.pass_at_least}, fail_at_most ${evaluation.fail_at_most}`,
    `minimum_evidence_completeness ${rule.minimum_evidence_completeness}`,
    `unknown → ${rule.unknown_evidence_policy}`,
    `conflicting → ${rule.conflicting_evidence_policy}`,
    hasLocalDecisionHook(rule)
      ? 'local_decision hook replaces numeric step 7'
      : 'no local_decision hook (numeric step 7)',
  ];
  return parts.join('; ');
}

function completenessPolicyCell(rule: RuleMetadata): string {
  const entries = Object.entries(rule.evidence_completeness ?? {});
  if (entries.length === 0) {
    return 'rank (default) for every type';
  }
  return entries.map(([type, policy]) => `\`${type}\`: ${policy}`).join(', ') + '; rank (default) for all other types';
}

/**
 * Pad a markdown table to the repo's prettier style (each column as wide as
 * its widest cell). Implemented here instead of importing prettier: prettier 3
 * is ESM-only and cannot load under ts-jest's CJS VM (no --experimental-vm-modules
 * in `npm test`). Code-point width matches prettier's string-width for the
 * BMP characters rule metadata uses; byte-parity with prettier output is
 * asserted by tests/scripts/gen-rule-catalog.test.ts.
 */
function padTable(header: string[], rows: string[][]): string {
  const width = (text: string): number => [...text].length;
  const widths = header.map((cell, i) => Math.max(width(cell), ...rows.map((row) => width(row[i]))));
  const line = (cells: string[]): string =>
    `| ${cells.map((cell, i) => cell + ' '.repeat(widths[i] - width(cell))).join(' | ')} |`;
  const separator = `| ${widths.map((w) => '-'.repeat(Math.max(3, w))).join(' | ')} |`;
  return [line(header), separator, ...rows.map(line)].join('\n');
}

/** One per-rule table; rows follow the Field schema table in catalog.md. */
export function renderRuleTable(rule: RuleMetadata): string {
  const rows: Array<[string, string]> = [
    ['Purpose', rule.description],
    ['Applicability', rule.applies_to.join(', ')],
    ['Required evidence', rule.required_evidence.map((type) => `\`${type}\``).join(', ')],
    ['Analysis scope', `\`${rule.analysis_scope}\``],
    ['Evaluation', evaluationCell(rule)],
    ['Evidence completeness policy', completenessPolicyCell(rule)],
    ['Rationale', rule.rationale ?? '—'],
    ['Limitations', rule.limitations ?? '—'],
    [
      'Lifecycle status',
      rule.deprecatedSince === undefined ? rule.status : `${rule.status} (deprecated since ${rule.deprecatedSince})`,
    ],
    ['Severity', rule.severity],
    ['Documentation reference', rule.docsUrl ?? '—'],
    [
      'Numeric-threshold honesty marker',
      rule.thresholds_inert === true ? '`thresholds_inert: true`' : 'absent (thresholds live)',
    ],
  ];
  return `### ${rule.id} — ${rule.name}\n\n${padTable(
    ['Catalog field', 'Value'],
    rows.map(([field, value]) => [field, cell(value)]),
  )}`;
}

export function renderGeneratedBlock(rules: readonly RuleMetadata[]): string {
  return [
    BEGIN_MARKER,
    '',
    '## Rule data tables',
    '',
    'Generated from `RuleMetadata` by `scripts/gen-rule-catalog.ts` — do not edit this section by hand; run the generator instead. Field semantics: the Field schema table above and `src/core/rule.ts`.',
    '',
    rules.map(renderRuleTable).join('\n\n'),
    '',
    END_MARKER,
  ].join('\n');
}

/** Replace the marked region in-place; on first run insert before the first `## CT-` section. */
export function replaceGeneratedRegion(doc: string, block: string): string {
  const begin = doc.indexOf(BEGIN_MARKER);
  const end = doc.indexOf(END_MARKER);
  if (begin !== -1 && end !== -1 && end > begin) {
    return doc.slice(0, begin) + block + doc.slice(end + END_MARKER.length);
  }
  if (begin !== -1 || end !== -1) {
    throw new Error('catalog.md has a mismatched GENERATED marker pair');
  }
  const anchor = doc.search(/^## CT-/m);
  if (anchor === -1) {
    throw new Error('catalog.md: no GENERATED markers and no "## CT-" section to anchor insertion');
  }
  return doc.slice(0, anchor) + block + '\n\n' + doc.slice(anchor);
}

/** @returns true when the file changed. */
export function generateCatalog(catalogPath: string): boolean {
  registerProductionRules();
  const rules = allRules();
  if (rules.length === 0) {
    throw new Error('no rules registered — refusing to generate an empty catalog');
  }
  const doc = readFileSync(catalogPath, 'utf8');
  const next = replaceGeneratedRegion(doc, renderGeneratedBlock(rules));
  if (next === doc) {
    return false;
  }
  writeFileSync(catalogPath, next);
  return true;
}

if (require.main === module) {
  const catalogPath = join(__dirname, '..', 'docs', 'rules', 'catalog.md');
  try {
    const changed = generateCatalog(catalogPath);
    process.stdout.write(`${changed ? 'updated' : 'unchanged'} ${catalogPath}\n`);
  } catch (error: unknown) {
    process.stderr.write(`gen-rule-catalog: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}
